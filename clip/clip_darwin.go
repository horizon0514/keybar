//go:build darwin

package clip

import (
	"runtime"
	"sync"
	"unsafe"

	"github.com/ebitengine/purego"
	"github.com/ebitengine/purego/objc"
)

// NSPasteboard through the Objective-C runtime (purego: no cgo). Called
// on the UI thread, as AppKit wants, each in its own autorelease pool.

var (
	macOnce sync.Once
	macOK   bool
	sel     = map[string]objc.SEL{}
)

// Types that password managers and others put on the pasteboard to say
// "do not keep or look at this" (nspasteboard.org).
var macSkip = map[string]bool{
	"org.nspasteboard.ConcealedType":         true,
	"org.nspasteboard.TransientType":         true,
	"org.nspasteboard.AutoGeneratedType":     true,
	"com.agilebits.onepassword":              true,
	"de.petermaurer.TransientPasteboardType": true,
	"Pasteboard generator type":              true,
}

func macLoad() bool {
	macOnce.Do(func() {
		if _, err := purego.Dlopen("/System/Library/Frameworks/AppKit.framework/AppKit", purego.RTLD_GLOBAL|purego.RTLD_NOW); err != nil {
			return
		}
		for _, s := range []string{"generalPasteboard", "changeCount", "types", "count", "objectAtIndex:", "stringForType:",
			"UTF8String", "lengthOfBytesUsingEncoding:", "alloc", "init", "drain", "initWithBytes:length:encoding:", "release", "length"} {
			sel[s] = objc.RegisterName(s)
		}
		macOK = objc.GetClass("NSPasteboard") != 0
	})
	return macOK
}

type mac struct{}

func system() (Board, bool, bool) { return mac{}, true, macLoad() }

const utf8Enc = 4 // NSUTF8StringEncoding

func pool(fn func()) {
	p := objc.ID(objc.GetClass("NSAutoreleasePool")).Send(sel["alloc"]).Send(sel["init"])
	defer p.Send(sel["drain"])
	fn()
}

func board() objc.ID { return objc.ID(objc.GetClass("NSPasteboard")).Send(sel["generalPasteboard"]) }

func (mac) Seq() (n uint64, ok bool) {
	if !macLoad() {
		return 0, false
	}
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	pool(func() { n = uint64(objc.Send[int](board(), sel["changeCount"])) })
	return n, true
}

func (mac) Read() (text string, skip bool) {
	if !macLoad() {
		return "", false
	}
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	pool(func() {
		b := board()
		types := b.Send(sel["types"])
		if types != 0 {
			for i := range objc.Send[uint](types, sel["count"]) {
				if t := goString(types.Send(sel["objectAtIndex:"], i), 256); macSkip[t] {
					skip = true
					return
				}
			}
		}
		key := "public.utf8-plain-text"
		ns := objc.ID(objc.GetClass("NSString")).Send(sel["alloc"]).Send(sel["initWithBytes:length:encoding:"],
			uintptr(unsafe.Pointer(unsafe.StringData(key))), uintptr(len(key)), uintptr(utf8Enc))
		runtime.KeepAlive(key)
		defer ns.Send(sel["release"])
		text = goString(b.Send(sel["stringForType:"], ns), Max)
	})
	return text, skip
}

// goString copies an NSString, "" when longer than max bytes.
func goString(s objc.ID, max int) string {
	if s == 0 {
		return ""
	}
	n := objc.Send[uint](s, sel["lengthOfBytesUsingEncoding:"], uintptr(utf8Enc))
	if n == 0 || int(n) > max {
		return ""
	}
	p := objc.Send[uintptr](s, sel["UTF8String"])
	if p == 0 {
		return ""
	}
	return string(unsafe.Slice(*(**byte)(unsafe.Pointer(&p)), n))
}
